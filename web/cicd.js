// Generates a GitOps pipeline for the user's own repository.
const CICD = (() => {
  const REPO = "Karthik-099/TERRAGUARD";

  function workflow(o) {
    const dir = o.dir || ".";
    const wd = dir === "." ? "" : `\n        working-directory: ${dir}`;
    const aws = o.cloud === "aws";
    const perms = ["contents: read", "pull-requests: write", "security-events: write"];
    if (aws) perms.push("id-token: write    # OIDC: short-lived AWS credentials, no stored keys");
    if (o.drift) perms.push("issues: write");
    const aiEnv = o.ai ? `\n        env:\n          ${o.ai.toUpperCase()}_API_KEY: \${{ secrets.${o.ai.toUpperCase()}_API_KEY }}` : "";
    const creds = aws ? `
      - name: Configure AWS credentials (OIDC)
        uses: aws-actions/configure-aws-credentials@v4
        with:
          role-to-assume: ${o.role || "arn:aws:iam::123456789012:role/terraform-plan"}
          aws-region: ${o.region || "us-east-1"}
` : "";

    const planSteps = `${creds}
      - name: terraform fmt
        run: terraform fmt -check -recursive${wd}

      - name: terraform init
        run: terraform init -input=false${wd}

      - name: terraform validate
        run: terraform validate -no-color${wd}

      - name: terraform plan
        id: plan${wd}
        run: |
          set +e
          terraform plan -input=false -no-color -detailed-exitcode -out=tfplan
          ec=$?
          echo "exitcode=$ec" >> "$GITHUB_OUTPUT"
          [ $ec -eq 1 ] && exit 1
          terraform show -json tfplan > plan.json

`;
    let y = `# Generated by TerraGuard — https://karthik-099.github.io/TERRAGUARD/
name: terraform

on:
  pull_request:
    paths: ["**/*.tf", "**/*.tfvars", ".terraguard.yml"]
  push:
    branches: [main]
    paths: ["**/*.tf", "**/*.tfvars", ".terraguard.yml"]${o.drift ? `
  schedule:
    - cron: "0 6 * * *"   # daily drift detection` : ""}
  workflow_dispatch:

permissions:
${perms.map((p) => "  " + p).join("\n")}

concurrency:
  group: terraform-\${{ github.ref }}
  cancel-in-progress: false   # never cancel a running apply

jobs:
  plan:
    runs-on: ubuntu-latest${o.plan ? `
    outputs:
      changes: \${{ steps.plan.outputs.exitcode == '2' }}` : ""}
    steps:
      - uses: actions/checkout@v4
      - uses: hashicorp/setup-terraform@v3
${o.plan ? planSteps : `      - name: terraform fmt
        run: terraform fmt -check -recursive${wd}

`}      - name: TerraGuard policy gate
        uses: ${REPO}@main
        with:
          path: ${dir}
${o.plan ? `          plan: ${dir === "." ? "" : dir + "/"}plan.json\n` : ""}          fail-on: ${o.failOn}
          comment: "true"
          sarif: "true"${o.ai ? `\n          ai: "true"` : ""}${aiEnv}
`;
    if (o.drift && o.plan) {
      y += `
      - name: Open an issue on drift
        if: github.event_name == 'schedule' && steps.plan.outputs.exitcode == '2'
        env:
          GH_TOKEN: \${{ github.token }}
        run: |
          gh issue create --repo "$GITHUB_REPOSITORY" \\
            --title "Terraform drift detected in ${dir} ($(date -u +%F))" \\
            --body "The scheduled plan found changes made outside Terraform. Run: $GITHUB_SERVER_URL/$GITHUB_REPOSITORY/actions/runs/$GITHUB_RUN_ID" \\
            --label drift || true
`;
    }
    if (o.apply && o.plan) {
      y += `
  apply:
    # GitOps: merging to main is the deploy. Requires approval on the
    # "production" environment (Settings → Environments → Required reviewers).
    needs: plan
    if: github.ref == 'refs/heads/main' && github.event_name == 'push' && needs.plan.outputs.changes == 'true'
    runs-on: ubuntu-latest
    environment: production
    steps:
      - uses: actions/checkout@v4
      - uses: hashicorp/setup-terraform@v3
${creds.replace("terraform-plan", "terraform-apply")}
      - run: terraform init -input=false${wd}
      - run: terraform apply -input=false -auto-approve${wd}
`;
    }
    return y;
  }

  const mcpClaude = () => `# Claude Code
go install github.com/${REPO}/cmd/terraguard@latest
claude mcp add terraguard -- terraguard mcp`;

  const mcpJson = () => JSON.stringify({ mcpServers: { terraguard: { command: "terraguard", args: ["mcp"] } } }, null, 2);

  const cli = () => `go install github.com/${REPO}/cmd/terraguard@latest

terraguard scan .                       # human-readable report, exit 1 on policy failure
terraguard scan . --format sarif > tg.sarif
terraguard scan . --plan plan.json      # add plan risk analysis
terraguard fix .                        # apply safe auto-fixes in place

# pre-commit hook (.git/hooks/pre-commit)
terraguard scan . --fail-on HIGH || exit 1`;

  const selfHost = () => `# Option A — single binary (keys stay in .env on the server)
git clone https://github.com/${REPO} && cd TERRAGUARD
cp .env.example .env            # add GROQ_API_KEY / OPENROUTER_API_KEY … or nothing at all
make web build && bin/terraguard serve      # http://127.0.0.1:8080

# Option B — Docker, with a private local LLM (nothing leaves your network)
docker compose --profile local-llm up -d
docker compose exec ollama ollama pull llama3.2
# open http://localhost:8080 → AI settings → "Self-hosted TerraGuard server"`;

  return { workflow, mcpClaude, mcpJson, cli, selfHost };
})();
