// Command ckvgen turns Checkov's declarative Terraform value checks
// (Apache-2.0) into TerraGuard rule-table entries, so the same controls are
// covered and checkov:skip comments map to them. Only checks whose whole logic
// is "this attribute must (not) have these values" are converted; anything
// with custom Python is left out. The engine's parity test then runs every
// generated rule against Checkov's own pass/fail fixtures.
//
//	go run ./tools/ckvgen -src path/to/checkov > /dev/null
package main

import (
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"
)

var (
	classRE    = regexp.MustCompile(`class \w+\((BaseResourceValueCheck|BaseResourceNegativeValueCheck)\)`)
	defRE      = regexp.MustCompile(`(?m)^    def (\w+)\(`)
	idRE       = regexp.MustCompile(`\bid\s*=\s*["'](CKV2?_[A-Z0-9]+_\d+)["']`)
	nameRE     = regexp.MustCompile(`\bname\s*=\s*\(?\s*((?:"[^"\n]*"\s*|'[^'\n]*'\s*)+)\)?`)
	typesRE    = regexp.MustCompile(`supported_resources\s*=\s*[\[(]([^\])]*)[\])]`)
	catRE      = regexp.MustCompile(`CheckCategories\.(\w+)`)
	strRE      = regexp.MustCompile(`"([^"]*)"|'([^']*)'`)
	missPassRE = regexp.MustCompile(`missing_block_result\s*=\s*CheckResult\.PASSED`)
	missFailRE = regexp.MustCompile(`missing_attribute_result\s*=\s*CheckResult\.FAILED`)
	prevIDRE   = regexp.MustCompile(`"(CKV2?_[A-Z0-9]+_\d+)":\s*"(TG-[A-Z0-9-]+)"`)
)

var prefixes = map[string]string{
	"aws": "AWS", "azurerm": "AZ", "azuread": "AZ", "google": "GCP", "kubernetes": "K8S", "alicloud": "ALI",
	"oci": "OCI", "digitalocean": "DO", "linode": "LIN", "openstack": "OS", "github": "GH", "gitlab": "GL",
	"tencentcloud": "TC", "yandex": "YC", "ncloud": "NCP", "panos": "PANOS", "okta": "OKTA",
}

type out struct {
	ckv, id, title, cat, sev, cwe, kind, path, why, remedy string
	types                                                  []string
	want                                                   []any
	missingOK, fixable, drop                               bool
}

func main() {
	src := flag.String("src", "", "checkov repository")
	fw := flag.String("framework", "terraform", "terraform, cloudformation or arm")
	flag.Parse()
	conf := frameworks[*fw]
	if conf.glob == "" {
		log.Fatalf("unknown framework %q", *fw)
	}
	framework = *fw
	dst := &conf.out
	known := map[string]bool{}
	if *fw == "terraform" {
		known = existingAliases("engine/aliases.go")
	}
	prev := map[string]string{}
	if b, err := os.ReadFile(*dst); err == nil {
		for _, m := range prevIDRE.FindAllStringSubmatch(string(b), -1) {
			prev[m[1]] = m[2]
		}
	}
	files, _ := filepath.Glob(filepath.Join(*src, conf.glob))
	var checks []out
	skipped := 0
	for _, f := range files {
		b, _ := os.ReadFile(f)
		c, ok := convert(string(b))
		if !ok {
			skipped++
			continue
		}
		if known[c.ckv] || dupOf[key(c.ckv)] != "" {
			continue // a hand-written rule already covers it
		}
		applyOverrides(&c)
		if c.drop {
			continue
		}
		checks = append(checks, c)
	}
	sort.Slice(checks, func(i, j int) bool { return ckvLess(checks[i].ckv, checks[j].ckv) })
	assignIDs(checks, prev)

	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by tools/ckvgen from Checkov's %s value checks (Apache-2.0, see NOTICE); DO NOT EDIT.\n\npackage engine\n\n", conf.label)
	fmt.Fprintf(&b, "var %sChecks = []check{\n", conf.prefix)
	for _, c := range checks {
		fmt.Fprintf(&b, "\t{ID: %q, Sev: %s, CWE: %q, Cat: %s, Title: %q, Types: %#v, Kind: %q, Path: %q", c.id, c.sev, c.cwe, c.cat, c.title, c.types, c.kind, c.path)
		if len(c.want) > 0 {
			fmt.Fprintf(&b, ", %s: []any{%s}", map[bool]string{true: "Bad", false: "Want"}[c.kind == "eq" || c.kind == "missing_or_eq"], goValues(c.want))
			if c.kind == "want" {
				fmt.Fprintf(&b, ", Good: %s", goValues(c.want[:1]))
			}
		}
		if c.missingOK {
			b.WriteString(", MissingOK: true")
		}
		if c.fixable {
			b.WriteString(", Fixable: true")
		}
		if c.why != "" {
			fmt.Fprintf(&b, ", Why: %q", c.why)
		}
		b.WriteString("},\n")
	}
	fmt.Fprintf(&b, "}\n\n// %sIDs maps each converted Checkov ID to its TerraGuard rule.\nvar %sIDs = map[string]string{\n", conf.prefix, conf.prefix)
	for _, c := range checks {
		fmt.Fprintf(&b, "\t%q: %q,\n", c.ckv, c.id)
	}
	fmt.Fprintf(&b, "}\n\n// %sCovered maps Checkov IDs that a hand-written rule already covers.\nvar %sCovered = map[string]string{\n", conf.prefix, conf.prefix)
	dupIDs := []string{}
	for k := range dupOf {
		fwk, ckv, qualified := strings.Cut(k, ":")
		if qualified && fwk == framework || !qualified && framework == "terraform" {
			if !qualified {
				ckv = k
			}
			dupIDs = append(dupIDs, ckv)
		}
	}
	sort.Slice(dupIDs, func(i, j int) bool { return ckvLess(dupIDs[i], dupIDs[j]) })
	for _, ckv := range dupIDs {
		fmt.Fprintf(&b, "\t%q: %q,\n", ckv, dupOf[key(ckv)])
	}
	fmt.Fprintf(&b, "}\n\nfunc init() {\n\tfor ckv, id := range %sIDs {\n\t\tforeignRules[ckv] = append(foreignRules[ckv], id)\n\t}\n\tfor ckv, id := range %sCovered {\n\t\tforeignRules[ckv] = append(foreignRules[ckv], id)\n\t}\n}\n", conf.prefix, conf.prefix)
	code, err := format.Source([]byte(b.String()))
	if err != nil {
		os.WriteFile(*dst+".broken", []byte(b.String()), 0o644)
		log.Fatal(err)
	}
	if err := os.WriteFile(*dst, code, 0o644); err != nil {
		log.Fatal(err)
	}
	log.Printf("%d converted, %d left for hand-written rules", len(checks), skipped)
	if framework == "terraform" {
		genGraph(*src, "engine/rules_graph_gen.go")
	}
}

type fwConf struct{ glob, out, prefix, label string }

var frameworks = map[string]fwConf{
	"terraform":      {"checkov/terraform/checks/resource/*/*.py", "engine/rules_parity.go", "parity", "Terraform"},
	"cloudformation": {"checkov/cloudformation/checks/resource/aws/*.py", "engine/rules_parity_cfn.go", "cfnParity", "CloudFormation"},
	"arm":            {"checkov/arm/checks/resource/*.py", "engine/rules_parity_azure_rm.go", "armParity", "ARM"},
}

// framework is the one being generated; non-Terraform keys in the .txt files
// are written framework:CKV_ID.
var framework = "terraform"

func key(ckv string) string {
	if framework == "terraform" {
		return ckv
	}
	return framework + ":" + ckv
}

func existingAliases(path string) map[string]bool {
	b, _ := os.ReadFile(path)
	out := map[string]bool{}
	for _, m := range regexp.MustCompile(`"(CKV2?_[A-Z0-9]+_\d+)"`).FindAllStringSubmatch(string(b), -1) {
		out[m[1]] = true
	}
	return out
}

func convert(py string) (out, bool) {
	cls := classRE.FindStringSubmatch(py)
	if cls == nil {
		return out{}, false
	}
	negative := cls[1] == "BaseResourceNegativeValueCheck"
	methods := map[string]string{}
	locs := defRE.FindAllStringSubmatchIndex(py, -1)
	for i, l := range locs {
		end := len(py)
		if i+1 < len(locs) {
			end = locs[i+1][0]
		}
		body := py[l[1]:end]
		if nl := strings.IndexByte(body, '\n'); nl >= 0 {
			if k := regexp.MustCompile(`(?m)^\S`).FindStringIndex(body[nl:]); k != nil {
				body = body[:nl+k[0]] // the method ends at the first unindented line
			}
		}
		methods[py[l[2]:l[3]]] = body
	}
	for m := range methods {
		switch m {
		case "__init__", "get_inspected_key", "get_expected_value", "get_expected_values", "get_forbidden_values":
		default:
			return out{}, false
		}
	}
	c := out{}
	if m := idRE.FindStringSubmatch(py); m != nil {
		c.ckv = m[1]
	}
	name := ""
	if m := nameRE.FindStringSubmatch(methods["__init__"]); m != nil {
		for _, s := range strRE.FindAllStringSubmatch(m[1], -1) {
			name += s[1] + s[2]
		}
	}
	if tm := typesRE.FindStringSubmatch(py); tm != nil {
		for _, s := range strRE.FindAllStringSubmatch(tm[1], -1) {
			c.types = append(c.types, s[1]+s[2])
		}
	}
	key, ok := returnLiteral(methods["get_inspected_key"])
	path, isStr := key.(string)
	if c.ckv == "" || name == "" || len(c.types) == 0 || !ok || !isStr || strings.ContainsAny(path, "*{}") {
		return out{}, false
	}
	c.path = toPath(path)
	category := "GENERAL_SECURITY"
	if m := catRE.FindStringSubmatch(py); m != nil {
		category = m[1]
	}
	if negative {
		v, ok := returnLiteral(methods["get_forbidden_values"])
		bad, isList := v.([]any)
		if !ok || !isList {
			return out{}, false
		}
		c.kind = "eq"
		if missFailRE.MatchString(py) {
			c.kind = "missing_or_eq"
		}
		for _, x := range bad {
			if x == anyValue {
				c.kind, bad = "present", nil
				break
			}
		}
		c.want = bad
	} else {
		want := []any{true}
		if body, ok := methods["get_expected_values"]; ok {
			v, ok := returnLiteral(body)
			l, isList := v.([]any)
			if !ok || !isList {
				return out{}, false
			}
			want = l
		} else if body, ok := methods["get_expected_value"]; ok {
			v, ok := returnLiteral(body)
			if !ok {
				return out{}, false
			}
			want = []any{v}
		}
		c.kind, c.want = "want", want
		if len(want) == 1 && want[0] == anyValue {
			c.kind, c.want = "set", nil
		}
		c.missingOK = missPassRE.MatchString(py)
		if c.missingOK && c.kind == "set" {
			return out{}, false // passes whatever is configured
		}
		// Auto-fix only when every parent is a block and the value is a plain scalar.
		segs := strings.Split(c.path, ".")
		_, isList := want[0].([]any)
		c.fixable = c.kind == "want" && len(want) == 1 && want[0] != nil && !isList
		for i := 0; i < len(segs)-1; i += 2 {
			if i+1 >= len(segs) || segs[i+1] != "0" {
				c.fixable = false
			}
		}
		if len(segs)%2 == 0 {
			c.fixable = false
		}
	}
	c.title = title(name)
	c.cat, c.sev, c.cwe = classify(category, name)
	return c, true
}

const anyValue = "__any__"

// returnLiteral parses `return <python literal>` as the method's only statement.
func returnLiteral(body string) (any, bool) {
	body = strings.TrimSpace(body)
	if i := strings.Index(body, ":"); i >= 0 {
		body = strings.TrimSpace(body[i+1:])
	}
	if strings.HasPrefix(body, `"""`) {
		if j := strings.Index(body[3:], `"""`); j >= 0 {
			body = strings.TrimSpace(body[j+6:])
		}
	}
	if !strings.HasPrefix(body, "return ") {
		return nil, false
	}
	expr := strings.TrimSpace(strings.TrimPrefix(body, "return "))
	if strings.Contains(expr, "\n") && !strings.HasPrefix(expr, "[") {
		return nil, false
	}
	p := &pyParser{s: expr}
	v, ok := p.value()
	p.skip()
	if !ok || strings.TrimSpace(p.s[p.i:]) != "" {
		return nil, false
	}
	return v, true
}

type pyParser struct {
	s string
	i int
}

func (p *pyParser) skip() {
	for p.i < len(p.s) && strings.ContainsRune(" \t\n\r,", rune(p.s[p.i])) {
		p.i++
	}
}

func (p *pyParser) value() (any, bool) {
	p.skip()
	if p.i >= len(p.s) {
		return nil, false
	}
	rest := p.s[p.i:]
	switch {
	case rest[0] == '[':
		p.i++
		var l []any
		for {
			p.skip()
			if p.i < len(p.s) && p.s[p.i] == ']' {
				p.i++
				return l, true
			}
			v, ok := p.value()
			if !ok {
				return nil, false
			}
			l = append(l, v)
		}
	case rest[0] == '"' || rest[0] == '\'':
		end := strings.IndexByte(rest[1:], rest[0])
		if end < 0 {
			return nil, false
		}
		p.i += end + 2
		str := rest[1 : end+1]
		if strings.HasPrefix(str, "${") && strings.HasSuffix(str, "}") {
			str = str[2 : len(str)-1] // Checkov's form of a plain HCL value
		}
		return str, true
	}
	word := regexp.MustCompile(`^[\w.\-]+`).FindString(rest)
	p.i += len(word)
	switch word {
	case "True":
		return true, true
	case "False":
		return false, true
	case "ANY_VALUE":
		return anyValue, true
	}
	if n, err := strconv.ParseFloat(word, 64); err == nil {
		return n, true
	}
	return nil, false
}

// toPath turns a/[0]/b into a.0.b, the engine's path form.
func toPath(p string) string {
	var segs []string
	for _, s := range strings.Split(strings.Trim(p, "/"), "/") {
		segs = append(segs, strings.Trim(s, "[]"))
	}
	return strings.Join(segs, ".")
}

var verbs = []struct{ from, to string }{
	{" is not ", " should not be "}, {" are not ", " should not be "}, {" does not ", " should not "}, {" do not ", " should not "},
	{" is ", " should be "}, {" are ", " should be "}, {" has ", " should have "}, {" have ", " should have "},
	{" uses ", " should use "}, {" use ", " should use "}, {" enables ", " should enable "}, {" requires ", " should require "},
	{" require ", " should require "}, {" contains ", " should contain "}, {" restricts ", " should restrict "},
	{" encrypts ", " should encrypt "}, {" allows ", " should allow "}, {" sets ", " should set "},
}

// title turns "Ensure X is encrypted" into "X should be encrypted".
func title(name string) string {
	t := strings.TrimSpace(name)
	t = regexp.MustCompile(`(?i)^(ensure|verify|check)( that)? `).ReplaceAllString(t, "")
	t = strings.TrimRight(t, ". ")
	for _, v := range verbs {
		if i := strings.Index(" "+t+" ", v.from); i >= 0 {
			t = t[:i] + v.to[1:len(v.to)-1] + t[i+len(v.from)-2:]
			t = strings.TrimSpace(strings.Replace(" "+t, "  ", " ", -1))
			break
		}
	}
	if t != "" {
		t = strings.ToUpper(t[:1]) + t[1:]
	}
	return t
}

func classify(category, name string) (cat, sev, cwe string) {
	n := strings.ToLower(name)
	cat, sev = "CatSecurity", "Medium"
	switch category {
	case "ENCRYPTION":
		cwe = "CWE-311"
	case "NETWORKING":
		cwe = "CWE-284"
	case "IAM":
		cwe, sev = "CWE-284", "High"
	case "LOGGING":
		cwe, sev = "CWE-778", "Low"
	case "BACKUP_AND_RECOVERY":
		cat, cwe, sev = "CatReliability", "CWE-693", "Low"
	case "SECRETS":
		cwe, sev = "CWE-798", "High"
	case "KUBERNETES":
		cwe = "CWE-250"
	case "SUPPLY_CHAIN":
		cwe = "CWE-1357"
	case "CONVENTION":
		cat, cwe, sev = "CatBestPrac", "CWE-1078", "Low"
	default:
		cwe = "CWE-693"
	}
	switch {
	case strings.Contains(n, "public") || strings.Contains(n, "0.0.0.0") || strings.Contains(n, "anonymous") || strings.Contains(n, "unauthenticated") || strings.Contains(n, "admin") || strings.Contains(n, "plaintext") || strings.Contains(n, "hard-coded") || strings.Contains(n, "hardcoded"):
		sev = "High"
	case strings.Contains(n, "tag") || strings.Contains(n, "description") || strings.Contains(n, "deletion protection"):
		if sev == "Medium" {
			sev = "Low"
		}
	}
	return cat, sev, cwe
}

func assignIDs(cs []out, prev map[string]string) { assignIDsFrom(cs, prev, 101) }

func assignIDsFrom(cs []out, prev map[string]string, start int) {
	used := map[string]bool{}
	for _, id := range prev {
		used[id] = true
	}
	next := map[string]int{}
	for i := range cs {
		if id, ok := prev[cs[i].ckv]; ok {
			cs[i].id = id
			continue
		}
		provider, rest, _ := strings.Cut(cs[i].types[0], "_")
		pfx := prefixes[provider]
		if pfx == "" {
			pfx = strings.ToUpper(provider)
		}
		svc, _, _ := strings.Cut(rest, "_")
		svc = strings.ToUpper(svc)
		switch t := cs[i].types[0]; {
		case strings.HasPrefix(t, "AWS::"): // AWS::S3::Bucket
			pfx, svc = "CFN", strings.ToUpper(strings.Split(t, "::")[1])
		case strings.HasPrefix(t, "Microsoft."): // Microsoft.Storage/storageAccounts
			pfx, svc = "ARM", strings.ToUpper(strings.TrimPrefix(strings.Split(t, "/")[0], "Microsoft."))
		}
		if svc == "" { // a provider-named type such as the http data source
			svc = "CORE"
		}
		if len(svc) > 10 {
			svc = svc[:10]
		}
		key := pfx + "-" + svc
		if next[key] == 0 {
			next[key] = start
		}
		for {
			id := fmt.Sprintf("TG-%s-%03d", key, next[key])
			next[key]++
			if !used[id] {
				used[id], cs[i].id = true, id
				break
			}
		}
	}
}

func ckvLess(a, b string) bool {
	pa, na := splitCKV(a)
	pb, nb := splitCKV(b)
	if pa != pb {
		return pa < pb
	}
	return na < nb
}

func splitCKV(id string) (string, int) {
	i := strings.LastIndex(id, "_")
	n, _ := strconv.Atoi(id[i+1:])
	return id[:i], n
}

func goValues(vs []any) string {
	parts := make([]string, len(vs))
	for i, v := range vs {
		switch t := v.(type) {
		case string:
			parts[i] = strconv.Quote(t)
		case float64:
			parts[i] = strconv.FormatFloat(t, 'f', -1, 64)
		case nil:
			parts[i] = "nil"
		case []any:
			parts[i] = "[]any{" + goValues(t) + "}"
		default:
			parts[i] = fmt.Sprint(t)
		}
	}
	return strings.Join(parts, ", ")
}

// dupOf maps Checkov IDs a hand-written rule already covers to that rule.
var dupOf = func() map[string]string {
	out := map[string]string{}
	var b []byte
	files, _ := filepath.Glob("tools/ckvgen/duplicates*.txt")
	for _, f := range files {
		c, _ := os.ReadFile(f)
		b = append(append(b, c...), '\n')
	}
	for _, line := range strings.Split(string(b), "\n") {
		if f := strings.Fields(line); len(f) == 2 && !strings.HasPrefix(line, "#") {
			out[f[0]] = f[1]
		}
	}
	return out
}()

var wording = func() map[string][]string {
	out := map[string][]string{}
	files, _ := filepath.Glob("tools/ckvgen/wording*.txt")
	for _, f := range files {
		b, _ := os.ReadFile(f)
		for _, line := range strings.Split(string(b), "\n") {
			if cols := strings.Split(line, "\t"); len(cols) >= 4 {
				out[cols[0]] = cols[1:]
			}
		}
	}
	return out
}()

// applyOverrides applies TerraGuard's own wording (tools/ckvgen/wording*.txt)
// and then tools/ckvgen/overrides.txt to one converted check.
func applyOverrides(c *out) {
	w := wording[key(c.ckv)]
	if w == nil && framework != "terraform" {
		w = wording[c.ckv] // the same control's Terraform wording
		if len(w) == 4 {
			w = []string{w[0], w[1], w[3]}
		}
	}
	if w != nil {
		c.title, c.why = w[0], w[1]
		if len(w) == 4 { // graph: title, why, remediation, severity
			c.remedy = w[2]
		}
		c.sev = w[len(w)-1]
	}
	var b []byte
	files, _ := filepath.Glob("tools/ckvgen/overrides*.txt")
	for _, f := range files {
		x, _ := os.ReadFile(f)
		b = append(append(b, x...), '\n')
	}
	for _, line := range strings.Split(string(b), "\n") {
		f := strings.Fields(line)
		if len(f) < 2 || f[0] != key(c.ckv) {
			continue
		}
		for _, o := range f[1:] {
			k, v, _ := strings.Cut(o, "=")
			switch k {
			case "sev":
				c.sev = v
			case "cat":
				c.cat = v
			case "missing_ok":
				c.missingOK = true
				if c.kind == "missing_or_eq" {
					c.kind = "eq"
				}
			case "drop":
				c.drop = true
			case "bad": // fire only on these values, | separated
				c.kind, c.want, c.missingOK, c.fixable = "eq", nil, false, false
				for _, w := range strings.Split(v, "|") {
					c.want = append(c.want, w)
				}
			case "want": // a corrected list of allowed values, | separated
				c.want = nil
				for _, w := range strings.Split(v, "|") {
					c.want = append(c.want, w)
				}
			}
		}
	}
}
