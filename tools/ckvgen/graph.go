// genGraph converts Checkov's YAML graph checks into built-in graph policies.
func genGraph(src, dst string) {
	prev := map[string]string{}
	if b, err := os.ReadFile(dst); err == nil {
		for _, m := range prevIDRE.FindAllStringSubmatch(string(b), -1) {
			prev[m[1]] = m[2]
		}
	}
	files, _ := filepath.Glob(filepath.Join(src, "checkov/terraform/checks/graph_checks/*/*.yaml"))
	type entry struct {
		out
		def, remedy string
	}
	var es []entry
	skipped := 0
	for _, f := range files {
		b, _ := os.ReadFile(f)
		p, err := engine.ParseGraphPolicy(string(b))
		if err != nil {
			skipped++
			continue
		}
		if dupOf[p.ID] != "" {
			continue // a hand-written rule covers it; mapped in rules_parity.go
		}
		var meta struct {
			Metadata struct{ Category string } `yaml:"metadata"`
		}
		yaml.Unmarshal(b, &meta)
		def, _ := json.Marshal(p.Def)
		types := reportedTypes(p.Def)
		if len(types) == 0 {
			skipped++
			continue
		}
		e := entry{out: out{ckv: p.ID, types: types, title: title(p.Title)}, def: string(def), remedy: describe(p.Def)}
		e.cat, e.sev, e.cwe = classify(strings.ToUpper(strings.ReplaceAll(meta.Metadata.Category, " ", "_")), p.Title)
		applyOverrides(&e.out)
		if e.out.drop {
			continue
		}
		if e.out.remedy != "" {
			e.remedy = e.out.remedy
		}
		es = append(es, e)
	}
	sort.Slice(es, func(i, j int) bool { return ckvLess(es[i].ckv, es[j].ckv) })
	outs := make([]out, len(es))
	for i := range es {
		outs[i] = es[i].out
	}
	assignIDsFrom(outs, prev, 301)
	var b strings.Builder
	b.WriteString("// Code generated by tools/ckvgen from Checkov's Terraform graph checks (Apache-2.0, see NOTICE); DO NOT EDIT.\n\npackage engine\n\n")
	b.WriteString("var graphGen = []graphGenEntry{\n")
	for i, e := range es {
		fmt.Fprintf(&b, "\t{Rule: Rule{ID: %q, Title: %q, Severity: %s, Category: %s, CWE: %q, Types: %#v, Remediation: %q}, Def: %q, Why: %q},\n",
			outs[i].id, outs[i].title, outs[i].sev, outs[i].cat, e.cwe, e.types, e.remedy, e.def, outs[i].why)
	}
	b.WriteString("}\n\n// graphIDs maps each converted Checkov ID to its TerraGuard rule.\nvar graphIDs = map[string]string{\n")
	for i, e := range es {
		fmt.Fprintf(&b, "\t%q: %q,\n", e.ckv, outs[i].id)
	}
	b.WriteString("}\n")
	code, err := format.Source([]byte(b.String()))
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(dst, code, 0o644); err != nil {
		log.Fatal(err)
	}
	log.Printf("graph: %d converted, %d with unsupported operators", len(es), skipped)
}

// reportedTypes are the resource types a policy reports on: the filter's
// types when it has one, otherwise every type it names.
func reportedTypes(c engine.GCond) []string {
	for _, s := range c.Sub {
		if s.Kind == "filter" {
			var out []string
			for _, v := range s.Value.([]any) {
				out = append(out, strings.TrimPrefix(fmt.Sprint(v), "data."))
			}
			return out
		}
	}
	seen := map[string]bool{}
	var out []string
	var walk func(engine.GCond)
	walk = func(c engine.GCond) {
		for _, t := range c.Types {
			t = strings.TrimPrefix(t, "data.")
			if t != "all" && !seen[t] {
				seen[t] = true
				out = append(out, t)
			}
		}
		for _, s := range c.Sub {
			walk(s)
		}
	}
	walk(c)
	return out
}

// describe writes the policy's requirement in words for the remediation.
func describe(c engine.GCond) string {
	var parts []string
	var walk func(engine.GCond, bool)
	walk = func(c engine.GCond, neg bool) {
		switch c.Kind {
		case "and", "or":
			for _, s := range c.Sub {
				walk(s, neg)
			}
		case "not":
			walk(c.Sub[0], !neg)
		case "connection":
			verb := "Connect"
			if c.Op == "not_exists" != neg {
				verb = "Do not connect"
			}
			parts = append(parts, fmt.Sprintf("%s %s to %s", verb, someTypes(c.Types), someTypes(c.Connected)))
		case "attribute":
			op := strings.ReplaceAll(c.Op, "_", " ")
			if neg {
				op = "not " + op
			}
			s := fmt.Sprintf("%s %s", c.Attr, op)
			if c.Value != nil && c.Op != "exists" && c.Op != "not_exists" {
				v, _ := json.Marshal(c.Value)
				s += " " + string(v)
			}
			parts = append(parts, s+" on "+someTypes(c.Types))
		}
	}
	walk(c, false)
	if len(parts) > 6 {
		parts = append(parts[:6], "and the remaining conditions")
	}
	return "Meet the policy: " + strings.Join(parts, "; ") + "."
}

// someTypes names up to three resource types.
func someTypes(ts []string) string {
	if len(ts) <= 3 {
		return strings.Join(ts, " or ")
	}
	return fmt.Sprintf("%s or %d similar resources", strings.Join(ts[:3], ", "), len(ts)-3)
}
