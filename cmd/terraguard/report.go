// runReport writes audit evidence for one compliance framework.
func runReport(args []string) (int, error) {
	fset := flag.NewFlagSet("report", flag.ContinueOnError)
	framework := fset.String("framework", "", "compliance framework: "+strings.Join(engine.ComplianceKeys, ", "))
	format := fset.String("format", "html", "html or json")
	out := fset.String("out", "", "write to this file instead of stdout")
	config := fset.String("config", "", "policy file (default: .terraguard.yml, found automatically)")
	paths, err := parseInterspersed(fset, args)
	if err != nil {
		return 2, err
	}
	if *format != "html" && *format != "json" {
		return 2, fmt.Errorf("unknown --format %q (html or json)", *format)
	}
	in, err := buildInput(paths, "", *config, "")
	if err != nil {
		return 2, err
	}
	in.Coverage = true // rules that ran without a finding count as applied
	cfg, err := engine.ParseConfig(in.Config)
	if err != nil {
		return 2, err
	}
	doc, err := engine.ComplianceReport(engine.Scan(in), cfg, *framework, time.Now())
	if err != nil {
		return 2, err
	}
	doc.FilesSHA256 = engine.FilesDigest(in.Files)
	b, err := renderReport(doc, *format)
	if err != nil {
		return 2, err
	}
	if *out != "" {
		return 0, os.WriteFile(*out, b, 0o644)
	}
	_, err = os.Stdout.Write(b)
	return 0, err
}

func renderReport(doc *engine.ComplianceDoc, format string) ([]byte, error) {
	if format == "json" {
		b, err := json.MarshalIndent(doc, "", "  ")
		return append(b, '\n'), err
	}
	var buf bytes.Buffer
	err := reportTmpl.Execute(&buf, doc)
	return buf.Bytes(), err
}

