package engine

import (
	"fmt"
	"sort"
	"strings"
)

// AgentsMD writes an AGENTS.md for a Terraform repository from the code and
// policy alone, so AI coding agents learn the repo's providers, commands,
// guardrails and boundaries without guessing. It is deterministic: re-run it
// in CI and diff the output to keep it current.
func AgentsMD(files map[string]string, policy string) string {
	m := Parse(files)
	cfg, err := ParseConfig(policy)
	if err != nil {
		cfg, _ = ParseConfig("")
	}
	var b strings.Builder
	b.WriteString("# AGENTS.md\n\nGenerated by `terraguard agents-md`. Instructions for AI coding agents working in this Terraform repository.\n\n## Repository\n\n")

	version, backend, providers := "not constrained", "none (local state)", []string{}
	for _, blk := range m.Blocks {
		if blk.Kind != "terraform" {
			continue
		}
		if v, ok := asString(blk.Attrs["required_version"]); ok {
			version = v
		}
		for _, rp := range blk.blocksAttr("required_providers") {
			for name, v := range rp {
				pm, _ := v.(map[string]any)
				src, _ := asString(pm["source"])
				ver, _ := asString(pm["version"])
				providers = append(providers, strings.TrimSpace(fmt.Sprintf("%s (%s %s)", name, src, ver)))
			}
		}
		for _, nb := range blk.body.Blocks {
			if nb.Type == "backend" && len(nb.Labels) > 0 {
				backend = nb.Labels[0]
			} else if nb.Type == "cloud" {
				backend = "HCP Terraform"
			}
		}
	}
	sort.Strings(providers)
	if len(providers) == 0 {
		seen := map[string]bool{}
		for _, r := range m.Resources {
			if p := providerOf(r.Address); p != "" && !seen[p] {
				seen[p] = true
				providers = append(providers, p+" (version not pinned)")
			}
		}
		sort.Strings(providers)
	}
	fmt.Fprintf(&b, "- Terraform version: `%s`\n- Providers: %s\n- State backend: %s\n- Resources: %d across %d file(s)\n",
		version, orDash(strings.Join(providers, ", ")), backend, len(m.Resources), len(files))
	var mods []string
	for _, blk := range m.Blocks {
		if blk.Kind == "module" && len(blk.Labels) == 1 {
			src, _ := asString(blk.Attrs["source"])
			mods = append(mods, fmt.Sprintf("`%s` (%s)", blk.Labels[0], src))
		}
	}
	if len(mods) > 0 {
		fmt.Fprintf(&b, "- Modules: %s\n", strings.Join(mods, ", "))
	}

	b.WriteString("\n## Commands\n\n" +
		"- Format: `terraform fmt -recursive`\n" +
		"- Validate without credentials: `terraform init -backend=false && terraform validate`\n" +
		"- Security, validation and policy (must pass before a PR): `terraguard scan .`\n" +
		"- Apply safe fixes: `terraguard fix .`\n" +
		"- Check only what your change introduces: `terraguard review --base origin/main .`\n" +
		"- Regenerate module docs: `terraguard docs . > README.md`\n")

	b.WriteString("\n## Layout\n\n")
	perFile := map[string]int{}
	for _, r := range m.Resources {
		perFile[r.File]++
	}
	names := make([]string, 0, len(files))
	for n := range files {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, n := range names {
		if strings.HasSuffix(n, ".tf") {
			fmt.Fprintf(&b, "- `%s`: %d resource(s)\n", n, perFile[n])
		}
	}

	fmt.Fprintf(&b, "\n## Guardrails (enforced by TerraGuard, gate at %s)\n\n", cfg.FailOn)
	b.WriteString("- Never hardcode secrets; use variables with `sensitive = true` or a secrets manager data source.\n" +
		"- Pin provider and module versions; never track a module's default branch.\n" +
		"- Keep storage and databases private and encrypted; never open admin ports (22, 3389, databases) to 0.0.0.0/0.\n" +
		"- Grant least-privilege IAM; never `Action = \"*\"` on `Resource = \"*\"`.\n")
	for _, cr := range cfg.CustomRules {
		title := cr.Title
		if title == "" {
			title = cr.Attribute
		}
		fmt.Fprintf(&b, "- `%s`: %s.\n", cr.ID, strings.TrimSuffix(title, "."))
	}

	b.WriteString("\n## Boundaries\n\n" +
		"- Do not run `terraform apply` or `terraform destroy`; changes ship through a pull request and the pipeline.\n" +
		"- Never commit `*.tfstate`, `.terraform/`, plan files or `.env`.\n")
	var stateful []string
	for _, r := range m.Resources {
		if r.Mode == "managed" && statefulTypes[r.Type] {
			stateful = append(stateful, "`"+r.Address+"`")
		}
	}
	if len(stateful) > 0 {
		fmt.Fprintf(&b, "- These resources hold data. Any change that forces their replacement needs explicit human approval: %s.\n", strings.Join(stateful, ", "))
	}
	if len(cfg.Waivers) > 0 {
		b.WriteString("- Accepted risks (waivers). Do not change these without asking the approver:\n")
		for _, w := range cfg.Waivers {
			fmt.Fprintf(&b, "  - `%s` on %s, approved by %s until %s: %s\n", w.Rule, orDash(w.Resource), orDash(w.ApprovedBy), orDash(w.Expires), w.Reason)
		}
	}
	return b.String()
}
